#!/usr/bin/env bash
# End-to-end Ethereum (canonical) rollout of the CCIP config policies on a
# mainnet Anvil fork.
#
# Flow:
#   1. Inject placeholder pools/peripheries for the four burn/mint chains, then
#      deploy CCIPTokenPoolConfig, CCIPTokenPoolConfigTimelock and
#      CCIPTokenPoolConfigProposalChecker (ccip_config_mainnet.json) and sync
#      their addresses into the OCG proposal registry.
#   2. Phase B (DAO MS): CCIPTokenPoolConfigBatch.prepareHandover, then a second
#      run that must propose nothing; then CCIPTokenPoolBatch.fundPool with the
#      amount it requires (the env.json minimum backing minus the unclaimable
#      balance of the pool) through a generated args file, with an empty re-run
#      that takes the free-liquidity early return on the Solana mint supply the
#      batch reads at build time.
#   3. Negative checks: the mainnet readiness report is RED and the proposal
#      build fails while the OHM fee budgets are still at the 90k default; then
#      the four mainnet lanes are mocked to 175k and readiness turns GREEN.
#   4. Phase C (OCG): executeOnAnvilFork.sh replays CCIPTokenPoolConfigProposal
#      (up to 13 actions: the read-only checker call first, then the handover
#      steps the live state still needs and the four addChain route actions)
#      from the timelock; the four routes must exist on the pool afterwards.
#   5. Post-OCG (DAO MS): CCIPRouteReconcileBatch.reconcileRoutes must propose
#      nothing on the converged routes; the timelock path is then exercised by
#      changing the desired outbound rate in env.json, reconciling (queues),
#      warping past the delay, executing (by id through the example args file
#      on a fresh timelock, where the queued action is action 1), and
#      reconciling again (empty). The periphery reconciler adds the four EVM
#      trusted remotes (nothing for solana) and proposes nothing on a re-run.
#   6. Containment: CCIPTokenPoolConfigBatch.disableChain from the DAO MS as
#      bridge_admin, an empty re-run through the Emergency MS variant, a
#      reconcileRoutes run without the restoreContained flag that lists the
#      route as contained and proposes nothing, then the declarative recovery
#      through the timelock with the flag.
#   7. Full halt: haltAll from the DAO MS must be refused (no emergency or admin
#      on mainnet); haltAllEmergencyMS from the Emergency MS contains every route
#      and disables both policies, with an empty re-run; reEnable from the DAO MS
#      inside the grace window, with an empty re-run; the limits of every route
#      are restored through the timelock with a restoreContained list naming
#      them all, after a run without the list that proposes nothing.
#   8. Print the final authority state.
#
# Usage:
#   ./run-ethereum.sh [--port <port>] [--keep-fork] [--use-deployed]
#
# --use-deployed: skip step 1 and rehearse against the config addresses already
#   in env.json / addresses.json (the real on-chain deployment).
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib/common.sh
source "$HERE/lib/common.sh"

CHAIN="mainnet"
SOLANA_SELECTOR="124615329519749607"
DISABLE_ARGS="src/scripts/ops/batches/args/CCIPTokenPoolConfigBatch_disableChain.json"
RESTORE_ARGS="src/scripts/ops/batches/args/CCIPRouteReconcileBatch_reconcileRoutes_restoreContained.json"
EXECUTE_ARGS="src/scripts/ops/batches/args/CCIPRouteReconcileBatch_executeReadyActions.json"
# Generated by the funding and halt steps; forge reads args files under deployments/ (fs_permissions)
FUND_ARGS="deployments/.ccip-harness-fundPool-${CHAIN}.json"
HALT_RESTORE_ARGS="deployments/.ccip-harness-restoreContained-${CHAIN}.json"

while [ $# -gt 0 ]; do
    case "$1" in
        --port)
            [ $# -ge 2 ] || die "--port requires a value"
            PORT="$2"
            RPC="http://localhost:${PORT}"
            shift 2
            ;;
        --keep-fork)
            KEEP_FORK="true"
            shift
            ;;
        --use-deployed)
            USE_DEPLOYED="true"
            shift
            ;;
        *) die "unknown argument: $1" ;;
    esac
done

cd "$REPO_ROOT"
load_dotenv
backup_tracked_files
trap cleanup EXIT

TIMELOCK="$(env_addr "$CHAIN" olympus.governance.Timelock)"
require_addr "$TIMELOCK" "$CHAIN olympus.governance.Timelock"

# The proposal resolves the remote pools of its four addChain actions from
# env.json; the burn/mint chains are not deployed on this single-chain fork.
inject_placeholder_contracts "$CHAIN"

start_anvil "$CHAIN"
fund "$DEPLOYER_ADDR"
fund "$TIMELOCK"

if [ "$USE_DEPLOYED" = "true" ]; then
    step "Using already-deployed config addresses from env.json (skipping deploy)"
else
    deploy_sequence "src/scripts/deploy/savedDeployments/ccip_config_mainnet.json"
fi

cfg="$(env_addr mainnet olympus.policies.CCIPTokenPoolConfig)"
require_addr "$cfg" "CCIPTokenPoolConfig"
tl="$(env_addr mainnet olympus.policies.CCIPTokenPoolConfigTimelock)"
require_addr "$tl" "CCIPTokenPoolConfigTimelock"
checker="$(env_addr mainnet olympus.periphery.CCIPTokenPoolConfigProposalChecker)"
require_addr "$checker" "CCIPTokenPoolConfigProposalChecker"
pool="$(env_addr mainnet olympus.periphery.CCIPLockReleaseTokenPool)"
require_addr "$pool" "CCIPLockReleaseTokenPool"
registry="$(env_addr mainnet external.ccip.TokenAdminRegistry)"
ohm="$(env_addr mainnet olympus.legacy.OHM)"
dao="$(env_addr mainnet olympus.multisig.dao)"
log "config=$cfg timelock=$tl checker=$checker pool=$pool"

step "Deployment checks"
echo "config.pool()                 = $(cast call "$cfg" 'pool()(address)' --rpc-url "$RPC")"
echo "timelock.config()             = $(cast call "$tl" 'config()(address)' --rpc-url "$RPC")"
echo "timelock.timelockDelay()      = $(cast call "$tl" 'timelockDelay()(uint48)' --rpc-url "$RPC")"
echo "config.gracePeriod()          = $(cast call "$cfg" 'gracePeriod()(uint32)' --rpc-url "$RPC")"
echo "timelock.gracePeriod()        = $(cast call "$tl" 'gracePeriod()(uint32)' --rpc-url "$RPC")"
echo "config.isLiquidityContainer() = $(cast call "$cfg" 'isLiquidityContainer()(bool)' --rpc-url "$RPC")"
echo "checker.CONFIG()              = $(cast call "$checker" 'CONFIG()(address)' --rpc-url "$RPC")"
echo "checker.CONFIG_TIMELOCK()     = $(cast call "$checker" 'CONFIG_TIMELOCK()(address)' --rpc-url "$RPC")"
echo "checker.POOL()                = $(cast call "$checker" 'POOL()(address)' --rpc-url "$RPC")"

step "Sync addresses.json (proposal registry)"
set_registry_addr olympus-policy-ccip-token-pool-config "$cfg"
set_registry_addr olympus-policy-ccip-token-pool-config-timelock "$tl"
set_registry_addr olympus-periphery-ccip-token-pool-config-proposal-checker "$checker"

step "Phase B: prepareHandover (DAO MS)"
run_batch CCIPTokenPoolConfigBatch prepareHandover dao
expect_non_empty_batch "$LAST_BATCH_LOG" "prepareHandover"
run_batch CCIPTokenPoolConfigBatch prepareHandover dao "" "-rerun"
expect_empty_batch "$LAST_BATCH_LOG" "prepareHandover re-run"

step "Fund the pool to the minimum backing (DAO MS)"
min_backing="$(jq -r '.current.mainnet.olympus.config.CCIP.minimumPoolBacking' "$REPO_ROOT/$ENV_JSON")"
unclaimable="$(jq -r '.current.mainnet.olympus.config.CCIP.poolUnclaimableBalance' "$REPO_ROOT/$ENV_JSON")"
pool_balance="$(cast call "$ohm" 'balanceOf(address)(uint256)' "$pool" --rpc-url "$RPC" | awk '{print $1}')"
dao_balance="$(cast call "$ohm" 'balanceOf(address)(uint256)' "$dao" --rpc-url "$RPC" | awk '{print $1}')"
# The amount is the key minus the unclaimable balance of the pool, the one value
# fundPool accepts (shell/calc_bridged_supply.sh prints it). The batch reads the
# Solana mint supply at build time, on the fork too (the solana alias of
# foundry.toml), so the re-run takes the free-liquidity early return on the
# live supply. The fork balance is frozen at the fork block while the supply is
# live: a lock minted on Solana after that block leaves the fork's free
# liquidity short by its amount and fails the re-run assertion; start the run
# again then.
fund_amount="$((min_backing - unclaimable))"
log "key=$min_backing unclaimable=$unclaimable pool=$pool_balance dao=$dao_balance amount=$fund_amount"
[ "$pool_balance" -lt "$min_backing" ] || die "the pool already holds the minimum backing on this fork; the funding step expects a shortfall"
if [ "$dao_balance" -lt "$fund_amount" ]; then
    # The live DAO MS balance covers the amount today; this branch keeps the
    # rehearsal green if it ever does not, by minting from the OHM vault (the
    # MINTR module, resolved through the token's authority rather than assumed).
    ohm_authority="$(cast call "$ohm" 'authority()(address)' --rpc-url "$RPC")"
    ohm_vault="$(cast call "$ohm_authority" 'vault()(address)' --rpc-url "$RPC")"
    top_up="$((fund_amount - dao_balance))"
    log "minting $top_up OHM to the DAO MS from the OHM vault $ohm_vault"
    cast_send_impersonated "$ohm_vault" "$ohm" "mint(address,uint256)" "$dao" "$top_up"
fi
jq -n --arg amount "$fund_amount" '{functions: [{name: "fundPool", args: {amount: $amount}}]}' > "$FUND_ARGS"
log "fundPool args: $(jq -c '.functions[0].args' "$FUND_ARGS")"
run_batch CCIPTokenPoolBatch fundPool dao "$FUND_ARGS"
expect_non_empty_batch "$LAST_BATCH_LOG" "fundPool"
run_batch CCIPTokenPoolBatch fundPool dao "$FUND_ARGS" "-rerun"
expect_empty_batch "$LAST_BATCH_LOG" "fundPool re-run"
expect_log_line "$LAST_BATCH_LOG" "The free liquidity of the pool already covers the minimum backing" "fundPool re-run took the free-liquidity early return"
rm -f "$FUND_ARGS"
echo "pool OHM balance = $(cast call "$ohm" 'balanceOf(address)(uint256)' "$pool" --rpc-url "$RPC")  (key=$min_backing)"

step "Negative: mainnet readiness must be RED before the fee budgets are raised"
if READINESS_RPC_MAINNET="$RPC" ./shell/ccip/check_rollout_readiness.sh --chains mainnet \
    > "$LOG_DIR/readiness-mainnet-red.log" 2>&1; then
    die "the readiness report was expected to be RED; see $LOG_DIR/readiness-mainnet-red.log"
fi
grep -q "READINESS RESULT mainnet: RED" "$LOG_DIR/readiness-mainnet-red.log" \
    || die "the readiness report did not print a RED verdict; see $LOG_DIR/readiness-mainnet-red.log"
log "OK: readiness is RED before the fee budget mock"

step "Negative: the proposal build must fail before the fee budgets are raised"
if RPC_URL="$RPC" src/scripts/proposals/executeOnAnvilFork.sh \
    --file src/proposals/CCIPTokenPoolConfigProposal.sol \
    --contract CCIPTokenPoolConfigProposalScript \
    > "$LOG_DIR/proposal-no-budget.log" 2>&1; then
    die "the proposal build was expected to fail; see $LOG_DIR/proposal-no-budget.log"
fi
grep -q "OHM delivery gas budget of the lane" "$LOG_DIR/proposal-no-budget.log" \
    || die "the proposal did not fail on the fee budgets; see $LOG_DIR/proposal-no-budget.log"
log "OK: the proposal build fails on the fee budgets before the mock"

step "Mock the OHM fee entries of the four mainnet lanes"
for peer in arbitrum optimism base berachain; do
    mock_ohm_fee_entry mainnet "$peer"
done

step "Readiness must be GREEN after the fee budget mock"
READINESS_RPC_MAINNET="$RPC" ./shell/ccip/check_rollout_readiness.sh --chains mainnet \
    2>&1 | tee "$LOG_DIR/readiness-mainnet-green.log"
grep -q "READINESS RESULT mainnet: GREEN" "$LOG_DIR/readiness-mainnet-green.log" \
    || die "the readiness report was expected to be GREEN; see $LOG_DIR/readiness-mainnet-green.log"

step "Phase C: execute CCIPTokenPoolConfigProposal from the timelock"
RPC_URL="$RPC" src/scripts/proposals/executeOnAnvilFork.sh \
    --file src/proposals/CCIPTokenPoolConfigProposal.sol \
    --contract CCIPTokenPoolConfigProposalScript \
    2>&1 | tee "$LOG_DIR/proposal.log"
grep -q "Proposal executed successfully" "$LOG_DIR/proposal.log" || die "proposal replay failed; see $LOG_DIR/proposal.log"

step "The four routes must exist on the pool after the proposal"
for peer in arbitrum optimism base berachain; do
    peer_sel="$(jq -r --arg c "$peer" '.current[$c].external.ccip.ChainSelector' "$REPO_ROOT/$ENV_JSON")"
    supported="$(cast call "$pool" 'isSupportedChain(uint64)(bool)' "$peer_sel" --rpc-url "$RPC")"
    [ "$supported" = "true" ] || die "the $peer route is missing on the pool after the proposal"
    log "route $peer (selector $peer_sel) is configured"
done

step "Post-OCG: reconcileRoutes on the converged routes (DAO MS)"
run_batch CCIPRouteReconcileBatch reconcileRoutes dao "" "-converged"
expect_empty_batch "$LAST_BATCH_LOG" "reconcileRoutes (converged: the proposal added the four routes)"

step "Periphery reconcile (DAO MS): four EVM trusted remotes, nothing for solana"
run_batch CCIPBridgeBatch reconcileTrustedRemotes dao
expect_non_empty_batch "$LAST_BATCH_LOG" "reconcileTrustedRemotes"
if grep -q "Added: setTrustedRemoteSVM\|Added: unsetTrustedRemoteSVM" "$LAST_BATCH_LOG"; then
    die "the periphery reconciler proposed a solana change on the migrated env; see $LAST_BATCH_LOG"
fi
run_batch CCIPBridgeBatch reconcileTrustedRemotes dao "" "-rerun"
expect_empty_batch "$LAST_BATCH_LOG" "reconcileTrustedRemotes re-run"

step "Timelock path: change the desired Solana outbound rate, reconcile, execute, reconcile"
orig_rate="$(jq -r '.current.mainnet.olympus.config.CCIP.routes.solana.outboundRateLimit.rate' "$REPO_ROOT/$ENV_JSON")"
new_rate="$((orig_rate + 1))"
set_env_value mainnet "olympus.config.CCIP.routes.solana.outboundRateLimit.rate" "\"$new_rate\""
log "desired outbound rate: $orig_rate -> $new_rate"
run_batch CCIPRouteReconcileBatch reconcileRoutes dao "" "-queue"
expect_non_empty_batch "$LAST_BATCH_LOG" "reconcileRoutes (queue setChainRateLimits)"
run_batch CCIPRouteReconcileBatch reconcileRoutes dao "" "-queue-rerun"
expect_empty_batch "$LAST_BATCH_LOG" "reconcileRoutes re-run (already queued)"
# The example args file names action 1, which is the queued action on a fresh timelock;
# against an already-deployed timelock with earlier actions, every ready action is executed
execute_args=""
if [ "$(cast call "$tl" 'nextActionId()(uint64)' --rpc-url "$RPC" | awk '{print $1}')" = "2" ]; then
    execute_args="$EXECUTE_ARGS"
    log "the queued action is action 1: executing by id through $EXECUTE_ARGS"
fi
run_batch CCIPRouteReconcileBatch executeReadyActions dao "$execute_args" "-early"
expect_empty_batch "$LAST_BATCH_LOG" "executeReadyActions before the delay"
[ -z "$execute_args" ] || expect_log_line "$LAST_BATCH_LOG" "Not ready: executable at" "executeReadyActions reports the listed action as not ready"
# cast appends a scientific-notation hint to large numbers; keep the first token only
delay="$(cast call "$tl" 'timelockDelay()(uint48)' --rpc-url "$RPC" | awk '{print $1}')"
warp "$((delay + 1))"
run_batch CCIPRouteReconcileBatch executeReadyActions dao "$execute_args" "-ready"
expect_non_empty_batch "$LAST_BATCH_LOG" "executeReadyActions after the delay"
run_batch CCIPRouteReconcileBatch reconcileRoutes dao "" "-after-execute"
expect_empty_batch "$LAST_BATCH_LOG" "reconcileRoutes after execution"
echo "outbound bucket = $(cast call "$pool" 'getCurrentOutboundRateLimiterState(uint64)((uint128,uint32,bool,uint128,uint128))' "$SOLANA_SELECTOR" --rpc-url "$RPC")"

step "Restore the desired rate and converge again"
set_env_value mainnet "olympus.config.CCIP.routes.solana.outboundRateLimit.rate" "\"$orig_rate\""
run_batch CCIPRouteReconcileBatch reconcileRoutes dao "" "-restore-queue"
expect_non_empty_batch "$LAST_BATCH_LOG" "reconcileRoutes (queue restore)"
warp "$((delay + 1))"
run_batch CCIPRouteReconcileBatch executeReadyActions dao "" "-restore-execute"
expect_non_empty_batch "$LAST_BATCH_LOG" "executeReadyActions (restore)"
run_batch CCIPRouteReconcileBatch reconcileRoutes dao "" "-restored"
expect_empty_batch "$LAST_BATCH_LOG" "reconcileRoutes after restore"

step "Containment (DAO MS) and declarative recovery"
run_batch CCIPTokenPoolConfigBatch disableChain dao "$DISABLE_ARGS"
expect_non_empty_batch "$LAST_BATCH_LOG" "disableChain (DAO MS)"
expect_eq "$(cast call "$cfg" 'isChainDisabled(uint64)(bool)' "$SOLANA_SELECTOR" --rpc-url "$RPC")" "true" "config.isChainDisabled(solana) after disableChain"
run_batch CCIPTokenPoolConfigBatch disableChainEmergencyMS emergency "$DISABLE_ARGS" "-rerun"
expect_empty_batch "$LAST_BATCH_LOG" "disableChainEmergencyMS re-run"
# Without the flag the reconciler leaves the containment in place and lists the route
run_batch CCIPRouteReconcileBatch reconcileRoutes dao "" "-contained-no-flag"
expect_empty_batch "$LAST_BATCH_LOG" "reconcileRoutes on the contained route without restoreContained"
expect_log_line "$LAST_BATCH_LOG" "Contained routes: limit restore skipped" "reconcileRoutes lists the contained route"
run_batch CCIPRouteReconcileBatch reconcileRoutes dao "$RESTORE_ARGS" "-recovery-queue"
expect_non_empty_batch "$LAST_BATCH_LOG" "reconcileRoutes (queue the limit restore with restoreContained)"
warp "$((delay + 1))"
run_batch CCIPRouteReconcileBatch executeReadyActions dao "" "-recovery-execute"
expect_non_empty_batch "$LAST_BATCH_LOG" "executeReadyActions (recovery)"
run_batch CCIPRouteReconcileBatch reconcileRoutes dao "" "-recovered"
expect_empty_batch "$LAST_BATCH_LOG" "reconcileRoutes after recovery"
expect_eq "$(cast call "$cfg" 'isChainDisabled(uint64)(bool)' "$SOLANA_SELECTOR" --rpc-url "$RPC")" "false" "config.isChainDisabled(solana) after the recovery"

step "Full halt (Emergency MS), grace-window reEnable (DAO MS) and declarative recovery"
# The DAO MS holds neither emergency nor admin on mainnet, so its variant is refused
run_batch_expect_fail CCIPTokenPoolConfigBatch haltAll dao "holds neither emergency nor admin" "" "-dao"
run_batch CCIPTokenPoolConfigBatch haltAllEmergencyMS emergency
expect_non_empty_batch "$LAST_BATCH_LOG" "haltAllEmergencyMS"
expect_routes_contained "$cfg" "$pool" "true" "after haltAllEmergencyMS"
expect_eq "$(cast call "$cfg" 'isEnabled()(bool)' --rpc-url "$RPC")" "false" "config.isEnabled() after haltAllEmergencyMS"
expect_eq "$(cast call "$tl" 'isEnabled()(bool)' --rpc-url "$RPC")" "false" "timelock.isEnabled() after haltAllEmergencyMS"
run_batch CCIPTokenPoolConfigBatch haltAllEmergencyMS emergency "" "-rerun"
expect_empty_batch "$LAST_BATCH_LOG" "haltAllEmergencyMS re-run"
run_batch CCIPTokenPoolConfigBatch reEnable dao
expect_non_empty_batch "$LAST_BATCH_LOG" "reEnable (DAO MS as bridge_admin, inside the grace window)"
expect_eq "$(cast call "$cfg" 'isEnabled()(bool)' --rpc-url "$RPC")" "true" "config.isEnabled() after reEnable"
expect_eq "$(cast call "$tl" 'isEnabled()(bool)' --rpc-url "$RPC")" "true" "timelock.isEnabled() after reEnable"
run_batch CCIPTokenPoolConfigBatch reEnable dao "" "-rerun"
expect_empty_batch "$LAST_BATCH_LOG" "reEnable re-run"
# Without the list the reconciler leaves every containment in place
run_batch CCIPRouteReconcileBatch reconcileRoutes dao "" "-halt-no-flag"
expect_empty_batch "$LAST_BATCH_LOG" "reconcileRoutes after the halt without restoreContained"
expect_log_line "$LAST_BATCH_LOG" "Contained routes: limit restore skipped" "reconcileRoutes lists the contained routes"
write_restore_all_args "$CHAIN" "$HALT_RESTORE_ARGS"
run_batch CCIPRouteReconcileBatch reconcileRoutes dao "$HALT_RESTORE_ARGS" "-halt-recovery-queue"
expect_non_empty_batch "$LAST_BATCH_LOG" "reconcileRoutes (queue the limit restore of every route)"
rm -f "$HALT_RESTORE_ARGS"
warp "$((delay + 1))"
run_batch CCIPRouteReconcileBatch executeReadyActions dao "" "-halt-recovery-execute"
expect_non_empty_batch "$LAST_BATCH_LOG" "executeReadyActions (halt recovery)"
run_batch CCIPRouteReconcileBatch reconcileRoutes dao "" "-halt-recovered"
expect_empty_batch "$LAST_BATCH_LOG" "reconcileRoutes after the halt recovery"
expect_routes_contained "$cfg" "$pool" "false" "after the halt recovery"

step "Post-run state"
roles_mod="$(env_addr mainnet olympus.modules.OlympusRoles)"
echo "pool.owner()                  = $(cast call "$pool" 'owner()(address)' --rpc-url "$RPC")  (config=$cfg)"
echo "pool pending owner (slot 0)   = $(cast storage "$pool" 0 --rpc-url "$RPC")"
echo "pool.getRebalancer()          = $(cast call "$pool" 'getRebalancer()(address)' --rpc-url "$RPC")  (timelock=$TIMELOCK)"
echo "pool.getRateLimitAdmin()      = $(cast call "$pool" 'getRateLimitAdmin()(address)' --rpc-url "$RPC")"
echo "config.configOperator()       = $(cast call "$cfg" 'configOperator()(address)' --rpc-url "$RPC")  (timelock policy=$tl)"
echo "config.isEnabled()            = $(cast call "$cfg" 'isEnabled()(bool)' --rpc-url "$RPC")"
echo "timelock.isEnabled()          = $(cast call "$tl" 'isEnabled()(bool)' --rpc-url "$RPC")"
echo "registry.getTokenConfig(OHM)  = $(cast call "$registry" 'getTokenConfig(address)((address,address,address))' "$ohm" --rpc-url "$RPC")"
echo "DAO MS bridge_admin           = $(cast call "$roles_mod" 'hasRole(address,bytes32)(bool)' "$dao" "$(cast format-bytes32-string bridge_admin)" --rpc-url "$RPC")"
echo "DAO MS bridge_rate_limiter    = $(cast call "$roles_mod" 'hasRole(address,bytes32)(bool)' "$dao" "$(cast format-bytes32-string bridge_rate_limiter)" --rpc-url "$RPC")"
echo "pool.getSupportedChains()     = $(cast call "$pool" 'getSupportedChains()(uint64[])' --rpc-url "$RPC")"
echo "outbound bucket (solana)      = $(cast call "$pool" 'getCurrentOutboundRateLimiterState(uint64)((uint128,uint32,bool,uint128,uint128))' "$SOLANA_SELECTOR" --rpc-url "$RPC")"
echo "inbound bucket (solana)       = $(cast call "$pool" 'getCurrentInboundRateLimiterState(uint64)((uint128,uint32,bool,uint128,uint128))' "$SOLANA_SELECTOR" --rpc-url "$RPC")"
echo "timelock.nextActionId()       = $(cast call "$tl" 'nextActionId()(uint64)' --rpc-url "$RPC")"

step "Ethereum CCIP config rollout complete"
log "config=$cfg timelock=$tl pool=$pool"
